'use strict';
const assert=require('node:assert/strict');
const S=require('../site/emotion-studio/shared-pixel-selection.js');
const W=64,H=112;
const rgba=new Uint8ClampedArray(W*H*4);
const at=(x,y)=>(y*W+x)*4;
rgba.set([201,12,16,255],at(8,30));
rgba.set([17,201,22,255],at(9,30));
rgba.set([33,42,230,255],at(9,31));
assert.deepEqual(S.opaqueBounds(rgba,W,H),{x:8,y:30,w:2,h:2});
assert.equal(S.opaqueBounds(new Uint8ClampedArray(W*H*4),W,H),null);
const clip={...S.copy(rgba,W,H,null),bone:'arm_near_upper',direction:'se'};
const tight={...S.copy(rgba,W,H,S.opaqueBounds(rgba,W,H)),bone:'arm_near_upper',direction:'se'};
assert.equal(clip.w,64,'legacy COPY without selection is full-plane');
assert.equal(tight.w,2,'fixed COPY must use tight opaque bounds');
const fromSame={selection:{x:8,y:30,w:2,h:2},direction:'se',bone:'arm_near_upper'};
const p=S.pasteTarget(tight,W,H,fromSame);
assert.deepEqual(p,{x:10,y:30,explicit:false},'source selection does not hijack target');
const placed=S.paste(rgba,W,H,tight,p);
assert.deepEqual(Array.from(placed.slice(at(10,30),at(10,30)+4)),[201,12,16,255]);
assert.deepEqual(Array.from(placed.slice(at(8,30),at(8,30)+4)),[201,12,16,255],'source remains unchanged');
const mirror=S.pasteTarget(tight,W,H,{...fromSame,mirror:true});
assert.deepEqual(mirror,{x:54,y:30,explicit:false},'PASTE FLIP reflects around whole canvas');
const flipped=S.paste(new Uint8ClampedArray(W*H*4),W,H,tight,{...mirror,mirror:true});
assert.deepEqual(Array.from(flipped.slice(at(54,30),at(54,30)+4)),[17,201,22,255],'mirrored image begins with rightmost source pixel');
assert.deepEqual(Array.from(flipped.slice(at(55,30),at(55,30)+4)),[201,12,16,255]);
const explicit=S.pasteTarget(tight,W,H,{selection:{x:4,y:6,w:2,h:2},direction:'se',bone:'arm_near_upper'});
assert.deepEqual(explicit,{x:4,y:6,explicit:true},'selected destination overrides default offset');
const cross=S.pasteTarget(tight,W,H,{direction:'sw',bone:'arm_near_upper'});
assert.deepEqual(cross,{x:8,y:30,explicit:false},'pasting into another view preserves source position unless flipped');
const nearEdge={...S.copy(rgba,W,H,{x:62,y:108,w:2,h:4}),bone:'a',direction:'se'};
assert.deepEqual(S.pasteTarget(nearEdge,W,H,{direction:'se',bone:'a'}),{x:60,y:108,explicit:false});
console.log('GENESIS PASTE QA: tight copy, same-view visible paste, flip position, target selection, opposite-view transfer: PASS');
