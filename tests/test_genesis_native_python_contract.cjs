"use strict";
const assert=require("node:assert/strict");
const C=require("../site/genesis-native-python-contract.js");
const a=C.make({id:"anim_test_native_001",name:"Standing Punch",template:"idle",frameCount:6,ms:120});
assert.equal(a.format,"genesis-v6b-native-animation-v1");
assert.deepEqual(Object.keys(a.poses),["se","sw","ne","nw"]);
assert.equal(a.poses.sw.length,6);
a.poses.se[2].joints.hand_near={x:39,y:58};
a.poses.se[2].angles.elbow_near=45;
const src=C.toPython(a);
assert.match(src,/^# Genesis V6B native animation/m);
assert.deepEqual(C.fromPython(src),a);
assert.throws(()=>C.fromPython("import os\nos.system('echo bad')"),/arbitrary Python/);
assert.throws(()=>C.fromPython(src+"print('bad')"),/arbitrary Python/);
const bad=structuredClone(a);bad.poses.ne[0].joints.hand_near.x=80;
assert.throws(()=>C.validate(bad),/outside/);
const missing=structuredClone(a);delete missing.poses.nw;
assert.throws(()=>C.validate(missing),/four directions/);
const key=structuredClone(a);key.id="walk";
assert.throws(()=>C.validate(key),/invalid animation id/);
assert.equal(C.TEMPLATES.length,11);
console.log("Genesis native Python contract OK");
