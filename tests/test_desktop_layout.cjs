'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const css=fs.readFileSync(path.join(__dirname,'../site/style.css'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../site/index.html'),'utf8');
assert.ok(css.includes('@media (min-width:781px){'),'desktop-only overrides missing');
assert.match(css,/\.desktop\{\s*height:100vh;height:100dvh;min-height:0;overflow:hidden;/);
assert.match(css,/\.workspace,\.animation-workspace\{\s*display:grid;flex:1 1 0;height:auto;min-height:0;/);
assert.match(css,/\.file-list\{min-height:0;overflow-y:auto;/);
assert.match(css,/\.detail-content\{min-height:0;overflow-y:auto;/);
assert.match(css,/\.detail-tabs\{\s*display:grid;grid-template-columns:repeat\(6,minmax\(0,1fr\)\)/);
assert.match(css,/\.detail-tabs > \.detail-tab:nth-child\(-n\+3\)\{grid-column:span 2\}/);
assert.match(css,/\.detail-tabs > \.detail-tab:nth-child\(n\+4\)\{grid-column:span 3\}/);
assert.match(css,/\.chrome-button,\.dir,\.file-filter,\.anim-filter,\.library-tab\{\s*display:inline-flex;align-items:center;justify-content:center;/);
assert.ok(css.includes('@media(max-width:780px){'),'existing mobile rules missing');
assert.ok(html.includes('style.css?v=desktop-viewport-fix-1'),'desktop styles not cache-busted');
assert.ok(html.includes('id="character-workspace"')&&html.includes('id="animation-workspace"'));
console.log('PASS Mahluk Hidup fixed-viewport desktop, internal scroll, centered controls, mobile preserved');
