for k, v in G.items():
    assert len(v) == 5 and len(set(map(len, v))) == 1, k
H = 5

def width(text, spacing=1):
    ws = [len(G.get(ch.upper(), G['?'])[0]) for ch in text]
    return sum(ws) + spacing * max(0, len(ws) - 1)

def draw(img, x, y, text, rgba, spacing=1):
    """Draw text with its top-left at (x, y) into a PIL RGBA image. Returns end x."""
    for ch in text:
        g = G.get(ch.upper(), G['?'])
        for j, row in enumerate(g):
            for i, c in enumerate(row):
                if c == '#':
                    px, py = x + i, y + j
                    if 0 <= px < img.width and 0 <= py < img.height:
                        img.putpixel((px, py), rgba)
        x += len(g[0]) + spacing
    return x
